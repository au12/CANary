#!/usr/bin/env python3
"""Pack the web UI (gzip) and the vehicle profiles into C sources for the firmware build."""
import argparse
import gzip
import hashlib
import json
import os

TYPES = {
    ".html": "text/html; charset=utf-8", ".css": "text/css", ".js": "application/javascript",
    ".svg": "image/svg+xml", ".png": "image/png", ".ico": "image/x-icon",
    ".json": "application/json", ".webmanifest": "application/manifest+json",
}


def c_bytes(data):
    out = []
    for i in range(0, len(data), 24):
        out.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    return "\n".join(out)


def c_string(text):
    lines = []
    for line in text.split("\n"):
        esc = line.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'    "{esc}\\n"')
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--web", required=True)
    ap.add_argument("--profiles", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--version", default="dev")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)

    names = sorted(n for n in os.listdir(a.web) if os.path.splitext(n)[1] in TYPES)
    names.sort(key=lambda n: n != "index.html")  # index.html first: it is the fallback page
    digest = hashlib.sha1()
    parts, table = [], []
    for i, name in enumerate(names):
        raw = open(os.path.join(a.web, name), "rb").read()
        digest.update(raw)
        gz = gzip.compress(raw, 9, mtime=0)
        parts.append(f"static const uint8_t a{i}[] = {{\n{c_bytes(gz)}\n}};")
        table.append(f'    {{"/{name}", "{TYPES[os.path.splitext(name)[1]]}", a{i}, {len(gz)}}},')
    build = f"{a.version}+{digest.hexdigest()[:8]}"
    with open(os.path.join(a.out, "web_assets.c"), "w") as f:
        f.write("/* Generated by tools/gen_assets.py. Do not edit. */\n#include \"app.h\"\n\n")
        f.write("\n".join(parts))
        f.write("\n\nconst web_asset g_web_assets[] = {\n" + "\n".join(table) + "\n};\n")
        f.write(f"const int g_web_asset_count = {len(names)};\nconst char g_web_build[] = \"{build}\";\n")

    profs = sorted(n for n in os.listdir(a.profiles) if n.endswith(".json"))
    with open(os.path.join(a.out, "profiles_data.c"), "w") as f:
        f.write("/* Generated by tools/gen_assets.py. Do not edit. */\n")
        f.write("typedef struct { const char *id; const char *json; } fw_profile;\n\n")
        rows = []
        for i, name in enumerate(profs):
            doc = json.load(open(os.path.join(a.profiles, name)))  # also validates
            text = json.dumps(doc, separators=(",", ":"), ensure_ascii=False)
            f.write(f"static const char p{i}[] =\n{c_string(text)};\n\n")
            rows.append(f'    {{"{name[:-5]}", p{i}}},')
        f.write("const fw_profile g_fw_profiles[] = {\n" + "\n".join(rows) + "\n};\n")
        f.write(f"const int g_fw_profile_count = {len(profs)};\n")


if __name__ == "__main__":
    main()
